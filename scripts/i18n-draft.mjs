#!/usr/bin/env node
// Machine-assisted catalog drafting. NOT a replacement for review.
//
//   node scripts/i18n-draft.mjs <locale> [--model gpt-4o-mini] [--force]
//
// Reads the missing-entry template for a locale (the same JSON that
// `npm run i18n -- --missing <locale>` prints), asks the OpenAI API to
// translate it in batches, and writes src/i18n/locales/<locale>.json.
//
// Placeholders are protected before the request and restored after, so a
// model that reorders a sentence still returns the same {name} tokens. Every
// batch is checked against the source shape; a batch that loses or invents a
// placeholder is retried, then reported so it can be fixed by hand.
//
// The result is a draft: `npm run i18n` still decides whether it ships.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(new URL('../package.json', import.meta.url)));
const LOCALES_DIR = path.join(ROOT, 'src/i18n/locales');

const [locale, ...flags] = process.argv.slice(2);
if (!locale) {
  console.error('usage: node scripts/i18n-draft.mjs <locale> [--model NAME] [--force]');
  process.exit(2);
}
const model = flags.includes('--model')
  ? flags[flags.indexOf('--model') + 1]
  : 'gpt-4o-mini';
const force = flags.includes('--force');
const batchSize = 60;

const apiKey = process.env.OPENAI_API_KEY;
if (!apiKey) {
  console.error('OPENAI_API_KEY is not set');
  process.exit(2);
}

const catalogPath = path.join(LOCALES_DIR, `${locale}.json`);
const existing = existsSync(catalogPath)
  ? JSON.parse(readFileSync(catalogPath, 'utf8'))
  : {};
if (Object.keys(existing).length && !force) {
  console.error(`${locale}.json already has entries; pass --force to redraft them`);
  process.exit(2);
}

// The template is regenerated by the project's own checker.
const { execFileSync } = await import('node:child_process');
const template = JSON.parse(
  execFileSync(
    process.execPath,
    ['scripts/i18n.mjs', '--missing', locale],
    { cwd: ROOT, maxBuffer: 64 * 1024 * 1024 },
  ),
);

const entries = Object.entries(template);
console.log(`${locale}: ${entries.length} entries, model ${model}`);

const PLACEHOLDER = /\{[A-Za-z0-9_]+\}/g;
const protect = (text, tokens) =>
  text.replace(PLACEHOLDER, (token) => {
    const index = tokens.push(token) - 1;
    return `\u0000${index}\u0000`;
  });
const restore = (text, tokens) =>
  text.replace(/\u0000(\d+)\u0000/g, (whole, index) =>
    tokens[Number(index)] ?? whole,
  );

const LOCALE_STYLE = {
  'zh-CN':
    'Simplified Chinese for users in mainland China. Address the user as 你. Keep HUD codes (HDG, BRG, CRS, FOV, DEST, SPD, RANGE, ALT) and keyboard keys (Space, Esc, Enter, Tab) in English. Keep the separators · — → ↗ … as-is. Space between Chinese and Latin text.',
  'zh-TW':
    'Traditional Chinese for users in Taiwan and Hong Kong. Address the user as 你. Use Taiwan terminology (資料, 網路, 攝影機, 衛星). Keep HUD codes and keyboard keys in English. Keep the separators · — → ↗ … as-is.',
  fr: 'Natural French for France. Address the user with « vous » or infinitive labels, consistent with a professional console. Sentence case.',
  de: 'Natural German. Address the user with « du » imperatives, concise console tone. Nouns capitalised. Sentence case for labels.',
  it: 'Natural Italian. Address the user with the informal « tu » imperative. Sentence case.',
  nl: 'Natural Dutch. Address the user with the informal « je ». Sentence case.',
  'pt-BR': 'Brazilian Portuguese. Address the user with the informal « você » imperative. Sentence case.',
  pl: 'Natural Polish. Use concise imperative forms. Sentence case.',
  sv: 'Natural Swedish. Address the user with the informal « du ». Sentence case.',
  cs: 'Natural Czech. Use concise imperative forms (formal or neutral). Sentence case.',
  ro: 'Natural Romanian. Address the user with the informal « tu » or neutral imperatives. Sentence case.',
  uk: 'Natural Ukrainian. Use concise imperative forms (Натисніть, Виберіть). Sentence case. Not Russian.',
  tr: 'Natural Turkish. Use concise imperative forms. Sentence case.',
  ja: 'Natural Japanese UI text. Use polite but concise forms (〜してください for instructions). Keep labels short. Keep Latin codes and keyboard keys in English.',
  ko: 'Natural Korean UI text. Use concise 해요체 for instructions. Keep Latin codes and keyboard keys in English.',
  hi: 'Natural Hindi UI text in Devanagari. Use concise imperative forms. Keep Latin codes and keyboard keys in English.',
  id: 'Natural Indonesian. Use concise imperative forms. Sentence case.',
  th: 'Natural Thai UI text. Use concise imperative forms. Keep Latin codes and keyboard keys in English.',
  vi: 'Natural Vietnamese. Use concise imperative forms. Sentence case.',
};

const style =
  LOCALE_STYLE[locale] ||
  'Natural, concise user-interface language for ' + locale;

const SYSTEM = `You translate user-interface strings for God's Eye View, a 3D globe intelligence console.
Target language: ${locale}.
${style}

Rules:
- Translate the VALUE only. Never translate or reorder the JSON keys.
- Keep every \\u0000N\\u0000 token exactly where it belongs; they stand for {placeholders}. Do not add or remove tokens.
- Do not translate product and provider names: Google Maps, Cesium ion, OpenAI, ChatGPT, NASA FIRMS, USGS, OpenSky, ADS-B, AIS, CCTV, HUD, TomTom, OpenStreetMap, Mapillary, YouTube, Facebook, X, Starlink, GNSS, GPS, GLONASS, Galileo.
- Keep UPPERCASE English UPPERCASE. Short chips and HUD readouts must stay short.
- Keep the separators · — → ↗ … and any leading/trailing spaces exactly.
- A string that is only a code, unit or abbreviation (CRT, NVG, FLIR, NOIR, HDG, N, S, E, W, N/A, REC) stays as it is.
- Output a single JSON object with the same keys and no commentary.
- For a plural entry the source is an object of English forms; return an object whose "other" (and any other category the target language needs) holds the translation.`;

async function translateBatch(batch, attempt = 1) {
  const tokens = [];
  const payload = {};
  for (const [key, value] of batch) {
    payload[key] =
      typeof value === 'string'
        ? protect(value, tokens)
        : Object.fromEntries(
            Object.entries(value).map(([form, text]) => [
              form,
              protect(text, tokens),
            ]),
          );
  }
  const response = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      authorization: `Bearer ${apiKey}`,
    },
    body: JSON.stringify({
      model,
      temperature: 0.2,
      response_format: { type: 'json_object' },
      messages: [
        { role: 'system', content: SYSTEM },
        {
          role: 'user',
          content: JSON.stringify(payload, null, 1),
        },
      ],
    }),
  });
  if (!response.ok) {
    const detail = await response.text();
    throw new Error(`OpenAI ${response.status}: ${detail.slice(0, 300)}`);
  }
  const data = await response.json();
  const text = data.choices?.[0]?.message?.content ?? '{}';
  let translated;
  try {
    translated = JSON.parse(text);
  } catch {
    if (attempt < 2) return translateBatch(batch, attempt + 1);
    throw new Error(`batch is not JSON: ${text.slice(0, 200)}`);
  }

  const problems = [];
  const result = {};
  for (const [key, value] of batch) {
    const got = translated[key];
    if (typeof value === 'string') {
      if (typeof got !== 'string') {
        problems.push(`${JSON.stringify(key)}: missing`);
        continue;
      }
      const out = restore(got, tokens);
      if (placeholderSignature(out) !== placeholderSignature(value)) {
        problems.push(`${JSON.stringify(key)}: placeholders`);
        continue;
      }
      result[key] = out;
    } else {
      if (!got || typeof got !== 'object') {
        problems.push(`${JSON.stringify(key)}: missing plural forms`);
        continue;
      }
      const forms = {};
      let ok = true;
      for (const [form, text] of Object.entries(value)) {
        const out = restore(String(got[form] ?? ''), tokens);
        if (placeholderSignature(out) !== placeholderSignature(text)) {
          problems.push(`${JSON.stringify(key)} [${form}]: placeholders`);
          ok = false;
          break;
        }
        forms[form] = out;
      }
      if (ok) result[key] = forms;
    }
  }
  return { result, problems };
}

const placeholderSignature = (text) =>
  [...String(text).matchAll(PLACEHOLDER)].map((m) => m[0]).sort().join(',');

const catalog = {};
let failedBatches = 0;

for (let start = 0; start < entries.length; start += batchSize) {
  const batch = entries.slice(start, start + batchSize);
  let attempt = 0;
  for (;;) {
    attempt += 1;
    try {
      const { result, problems } = await translateBatch(batch);
      Object.assign(catalog, result);
      if (problems.length) {
        console.warn(`batch ${start + 1}: ${problems.length} fixes needed`);
      }
      break;
    } catch (error) {
      if (attempt >= 3) {
        failedBatches += 1;
        console.error(`batch ${start + 1} failed: ${error.message}`);
        break;
      }
      await new Promise((resolve) => setTimeout(resolve, 1500 * attempt));
    }
  }
  const done = Math.min(start + batchSize, entries.length);
  console.log(`${locale}: ${done}/${entries.length}`);
}

writeFileSync(catalogPath, `${JSON.stringify(catalog, null, 2)}\n`);
console.log(
  `${locale}: wrote ${Object.keys(catalog).length}/${entries.length} entries, ${failedBatches} failed batches`,
);
